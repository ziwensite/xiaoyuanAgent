import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  // 与 tsconfig 的 target 保持一致，避免 tsc 放行的语法被 esbuild 降级成另一套
  target: "es2020",
  logLevel: "info",
  // obsidian 直接加载 main.js，文件越小冷启动越快；插件不需要可读的产物
  minify: prod,
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();

  // styles.css 不参与 esbuild 打包（Obsidian 直接读取原文件），
  // 因此改 CSS 时 esbuild 不会重编。这里额外监听它，变化时 touch 一下
  // main.js，触发 Obsidian 热加载插件重新加载本插件，使新样式立即生效。
  try {
    let pending = null;
    fs.watch("styles.css", () => {
      // 编辑器一次保存常触发多次事件，做个防抖避免连续 touch。
      if (pending) clearTimeout(pending);
      pending = setTimeout(() => {
        pending = null;
        try {
          const now = new Date();
          fs.utimesSync("main.js", now, now);
          console.log("[watch] styles.css changed -> touched main.js");
        } catch (err) {
          console.warn("[watch] failed to touch main.js:", err);
        }
      }, 100);
    });
  } catch (err) {
    console.warn("[watch] cannot watch styles.css:", err);
  }
}
